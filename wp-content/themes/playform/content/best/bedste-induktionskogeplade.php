<h2>Sådan vælger du en induktionskogeplade</h2>
<p>Induktion varmer med et magnetfelt, der sætter gang i varmen direkte i gryden. Det giver hurtig opkogning og præcis kontrol. Her er det, der adskiller pladerne.</p>
<h3>60 eller 80 cm?</h3>
<p>Den vigtigste ting at måle er udskæringen i bordpladen. En 60 cm-plade passer til de fleste standardkøkkener og har fire zoner. En plade på 80 cm har ofte også fire zoner, men de ligger længere fra hinanden, så store gryder og pander ikke støder sammen, og der er tit en lang flexzone. Skifter du en gammel plade ud, så tjek producentens mål for udskæringen, før du køber – mål på pladen selv er ikke det samme som hullet i bordet.</p>
